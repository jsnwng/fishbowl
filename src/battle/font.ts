export const GLYPH_W = 5;
export const GLYPH_H = 7;
const GAP = 1;

/** How wide a string is in pixels, at 1x. */
export const textWidth = (s: string) => (s.length ? s.length * (GLYPH_W + GAP) - GAP : 0);

/**
 * Paints `text` (upper-cased) with a 1px drop shadow, so it reads over sky and water alike.
 * The canvas is the text's size plus the shadow.
 */
export function paintText(text: string, color = '#ffffff', shadow = '#1a1a1a'): HTMLCanvasElement {
  const s = text.toUpperCase();
  const canvas = document.createElement('canvas');
  canvas.width = Math.max(1, textWidth(s) + 1);
  canvas.height = GLYPH_H + 1;
  const ctx = canvas.getContext('2d')!;
  for (const [fill, off] of [
    [shadow, 1],
    [color, 0],
  ] as const) {
    ctx.fillStyle = fill;
    [...s].forEach((ch, i) => {
      const g = GLYPHS[ch] ?? GLYPHS[' '];
      g.forEach((row, y) => {
        for (let x = 0; x < GLYPH_W; x++) if (row[x] === '#') ctx.fillRect(i * (GLYPH_W + GAP) + x + off, y + off, 1, 1);
      });
    });
  }
  return canvas;
}
